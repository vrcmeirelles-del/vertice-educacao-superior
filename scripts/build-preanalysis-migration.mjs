// Deterministic, narrower LOCAL canary. This script never connects to a database.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {pathToFileURL} from 'node:url';

export const CANARY_MIGRATION_PATH='supabase/migrations/20261112122340_superior_preanalysis_canary.sql';
const root=new URL('../',import.meta.url);
const tables=new Set(['vertice_private.preanalysis_policy','vertice_private.preanalysis_daily_usage','vertice_private.preanalysis_actor_usage','public.vertice_evidence_preanalysis_runs','vertice_private.preanalysis_run_authorizations','public.vertice_evidence_preanalysis_decisions']);

export function assertCanaryScope(sql){
 const code=sql.replace(/^\s*--[^\n]*$/gm,'');
 assert(!/\b(?:create|alter|drop)\s+(?:constraint\s+)?trigger\b/i.test(code),'Canary must not install triggers');
 assert(!/\b(?:preanalysis_events|preanalysis_enqueue|queue_enabled)\b/i.test(code),'Canary must not install the queue');
 assert(!/\b(?:grant|revoke)\s+[^;]*\bon\s+schema\b/i.test(code),'Canary must not modify existing schema privileges');
 assert(!/\b(?:create\s+or\s+replace|alter|drop)\s+function\b/i.test(code),'Canary must not replace existing functions');
 const created=[...code.matchAll(/\bcreate\s+table\s+([a-z_]+\.[a-z_]+)/gi)].map(m=>m[1]);
 assert.deepEqual(created,[...tables],'Unexpected canary table set');
 for(const pattern of [/\breferences\s+([a-z_]+\.[a-z_]+)/gi,/\balter\s+table\s+([a-z_]+\.[a-z_]+)/gi,/\b(?:insert\s+into|update|delete\s+from)\s+([a-z_]+\.[a-z_]+)/gi]){
  for(const match of code.matchAll(pattern))assert(tables.has(match[1]),`Canary changes or adds FK triggers to existing relation ${match[1]}`);
 }
 assert.equal([...code.matchAll(/\bcreate\s+function\b/gi)].length,12,'Unexpected canary function count');
 assert.equal([...code.matchAll(/\bcreate\s+policy\b/gi)].length,2,'Unexpected canary policy count');
 return {tables:created.length,functions:12,policies:2,sourceTriggers:0,existingRelationWrites:0};
}

export function buildCanaryMigration(proposal){
 let output=proposal;
 const replaceOnce=(pattern,replacement)=>{
  const matches=[...output.matchAll(new RegExp(pattern.source,pattern.flags.includes('g')?pattern.flags:pattern.flags+'g'))];
  assert.equal(matches.length,1,`Expected exactly one canary exclusion: ${pattern}`);
  output=output.replace(pattern,replacement);
 };
 replaceOnce(/^-- LOCAL CANDIDATE ONLY\.[\s\S]*?\nbegin;\n/,
  '-- LOCAL CANARY CANDIDATE ONLY. Never applied remotely; explicit approval is required.\n'+
  '-- Generated by scripts/build-preanalysis-migration.mjs from docs/sql/preanalysis-v2.sql.\n'+
  '-- Only new preanalysis tables/functions/policies. No queue, source triggers or schema grants.\n'+
  '-- External institution/course FKs are omitted to avoid internal triggers on existing tables;\n'+
  '-- authorized RPCs validate those references. Existing session helper is neither changed nor granted.\n'+
  'begin;\n');
 replaceOnce(/create table vertice_private\.preanalysis_events \([\s\S]*?\n\);\n/,'');
 replaceOnce(/create function vertice_private\.preanalysis_enqueue\(\)[\s\S]*?-- must obtain a fresh user-authorized descriptor\. No automatic retries or provider worker shipped\.\n/,'');
 replaceOnce(/ enabled boolean not null default false, queue_enabled boolean not null default false,/,' enabled boolean not null default false,');
 replaceOnce(/grant usage on schema vertice_private to service_role;\n/,'');
 replaceOnce(/revoke all on function vertice_private\.preanalysis_enqueue\(\) from public,anon,authenticated,service_role;\n/,'');
 replaceOnce(/alter table vertice_private\.preanalysis_events enable row level security;\nrevoke all on vertice_private\.preanalysis_events from public,anon,authenticated,service_role;\n/,'');
 assert.equal((output.match(/ references public\.vertice_institutions\(id\)/g)||[]).length,2);
 output=output.replaceAll(' references public.vertice_institutions(id)','');
 replaceOnce(/ references public\.vertice_courses\(id\)/,'');
 assertCanaryScope(output);
 return output;
}

if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const output=buildCanaryMigration(readFileSync(new URL('docs/sql/preanalysis-v2.sql',root),'utf8'));
 const destination=new URL(CANARY_MIGRATION_PATH,root);
 if(process.argv.includes('--check'))assert.equal(readFileSync(destination,'utf8'),output,'Local canary migration is stale; regenerate and review it');
 else writeFileSync(destination,output);
 console.log(JSON.stringify({file:CANARY_MIGRATION_PATH,sha256:createHash('sha256').update(output).digest('hex'),...assertCanaryScope(output)}));
}
