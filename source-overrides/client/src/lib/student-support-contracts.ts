// Contracts checked against the live public schema on 2026-11-12. No schema changes.
export const supportOrigins = ['estudante', 'secretaria', 'coordenacao', 'professor', 'fato_e_ordem'];
export const specialOrigins = ['estudante', 'secretaria', 'coordenacao', 'nucleo_apoio', 'professor', 'representante'];
export const accommodationCategories = ['metodologica', 'material_acessivel', 'comunicacao', 'tecnologia_assistiva', 'avaliativa', 'acessibilidade_fisica', 'acessibilidade_digital', 'atividade_pratica', 'estagio', 'outra'];
type Row = { id: string; institution_id: string; student_name?: string; student_matricula?: string; course_id?: string; code?: string; category_code?: string };
type Context = { institutionId: string; cases: Row[]; plans?: Row[]; categories?: Row[]; role?: string };
type Form = Record<string, string | boolean>;
const text = (f: Form, key: string) => String(f[key] ?? '').trim();
const required = (value: string, label: string) => { if (!value) throw new Error(`Informe ${label}.`); return value; };
const choice = (value: string, allowed: string[]) => { if (!allowed.includes(value)) throw new Error('Opção inválida para este formulário.'); return value; };
function parent(rows: Row[], id: string, institutionId: string) {
  const row = rows.find(r => r.id === id && r.institution_id === institutionId);
  if (!row) throw new Error('Selecione um vínculo válido da instituição atual.');
  return row;
}
function dates(f: Form, start: string, end: string) {
  const a = text(f, start), b = text(f, end);
  for (const value of [a,b]) if (value && (!/^\d{4}-\d{2}-\d{2}$/.test(value) || !Number.isFinite(Date.parse(value)) || new Date(value).toISOString().slice(0,10)!==value)) throw new Error('Data inválida.');
  if (a && b && a > b) throw new Error('A data final deve ser igual ou posterior à inicial.');
  return {[start]: a || null, [end]: b || null};
}
export function buildSupportPayload(kind: string, f: Form, ctx: Context): Record<string, unknown> {
  const institution_id = required(ctx.institutionId, 'a instituição');
  const common = {institution_id};
  const caseRow = () => parent(ctx.cases, text(f, 'case_id'), institution_id);
  const name = () => required(text(f, 'student_name'), 'o nome do estudante');
  const description = () => required(text(f, 'description'), 'a descrição');
  switch (kind) {
    case 'supportCase': return {...common, student_name:name(), student_matricula:text(f,'student_matricula')||null, priority:choice(text(f,'priority'),['baixa','normal','alta','urgente']), status:'solicitacao_recebida', summary:text(f,'summary')||null}; // protocol is generated by the existing DB trigger.
    case 'supportRequest': {
      const c = text(f,'case_id') ? caseRow() : null;
      return {...common, case_id:c?.id||null, student_name:c?.student_name||null, student_matricula:c?.student_matricula||null, origin:choice(text(f,'origin'),supportOrigins), needs_type:text(f,'needs_type')||null, description:description(), requester_name:text(f,'requester_name')||null, status:'pendente'};
    }
    case 'supportPlan': {
      const c=caseRow();
      return {...common,case_id:c.id,student_name:required(c.student_name||'','o estudante do caso'),student_matricula:c.student_matricula||null,course_id:c.course_id||null,objectives:text(f,'objectives') ? [text(f,'objectives')] : [],...dates(f,'effective_from','effective_until'),status:'em_elaboracao'};
    }
    case 'accommodation': return {...common,plan_id:parent(ctx.plans||[],text(f,'plan_id'),institution_id).id,category:choice(text(f,'category'),accommodationCategories),description:description(),responsible:text(f,'responsible')||null,status:'prevista'};
    case 'specialCase': {
      const cat = text(f,'category_id') ? parent(ctx.categories||[],text(f,'category_id'),institution_id) : null;
      return {...common,protocol:`AE-${crypto.randomUUID()}`,student_name:name(),student_matricula:text(f,'student_matricula')||null,category_id:cat?.id||null,category_code:cat?.code||null,status:'solicitacao_recebida',notes:text(f,'notes')||null};
    }
    case 'specialRequest': {
      const c=caseRow();
      const code=text(f,'category_code');
      if (code && !(ctx.categories||[]).some(r=>r.institution_id===institution_id && r.code===code)) throw new Error('Categoria inválida para esta instituição.');
      return {...common,case_id:c.id,student_name:required(c.student_name||'','o estudante do caso'),student_matricula:c.student_matricula||null,origin:choice(text(f,'origin'),specialOrigins),category_code:code||c.category_code||null,description:description(),requester_name:text(f,'requester_name')||null,...dates(f,'requested_period_start','requested_period_end'),status:'pendente'};
    }
    case 'specialDecision': return {...common,case_id:caseRow().id,authority_role:required(ctx.role||'','o perfil da autoridade'),decision_type:choice(text(f,'decision_type'),['deferimento','indeferimento','deferimento_parcial']),justification:required(text(f,'justification'),'a justificativa'),conditions:text(f,'conditions')||null,authority_name:text(f,'authority_name')||null,...dates(f,'regime_start','regime_end'),status:'vigente'};
    case 'specialPlan': {
      const c=caseRow();
      return {...common,case_id:c.id,student_name:required(c.student_name||'','o estudante do caso'),category_code:c.category_code||null,...dates(f,'plan_start','plan_end'),notes:text(f,'notes')||null,status:'rascunho'}; // No free-text name in elaborated_by (UUID), and no automatic approval/activation.
    }
    case 'specialCategory': return {...common,code:required(text(f,'code'),'o código'),label:required(text(f,'label'),'o nome'),description:text(f,'description')||null,legal_basis:text(f,'legal_basis')||null,requires_documentation:f.requires_documentation===true,active:true};
    default: throw new Error('Formulário desconhecido.');
  }
}
export function readableObjectives(value: unknown): string {
  if (typeof value === 'string') return value;
  if (value == null) return '';
  if (Array.isArray(value)) return value.map(v => typeof v === 'string' ? v : JSON.stringify(v)).join('; ');
  return JSON.stringify(value);
}
export async function checkedWrite(operation: PromiseLike<{error: unknown}>) {
  const result = await operation;
  if (result.error) throw new Error('Não foi possível salvar. Verifique as permissões e os dados e tente novamente.');
}
